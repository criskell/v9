#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum Condition {
    Eq = 0,
    Ne = 1,
    Hs = 2,
    Lo = 3,
    Mi = 4,
    Pl = 5,
    Vs = 6,
    Vc = 7,
    Hi = 8,
    Ls = 9,
    Ge = 10,
    Lt = 11,
    Gt = 12,
    Le = 13,
    Al = 14,
    Nv = 15,
}

pub const CS: Condition = Condition::Hs;
pub const CC: Condition = Condition::Lo;

pub fn negate_condition(cond: Condition) -> Condition {
    debug_assert!((cond != Condition::Al) && (cond != Condition::Nv));
    match cond as u32 ^ 1 {
        0 => Condition::Eq,
        1 => Condition::Ne,
        2 => Condition::Hs,
        3 => Condition::Lo,
        4 => Condition::Mi,
        5 => Condition::Pl,
        6 => Condition::Vs,
        7 => Condition::Vc,
        8 => Condition::Hi,
        9 => Condition::Ls,
        10 => Condition::Ge,
        11 => Condition::Lt,
        12 => Condition::Gt,
        13 => Condition::Le,
        _ => unreachable!(),
    }
}

